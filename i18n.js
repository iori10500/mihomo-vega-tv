export function resolveLanguage(preference, systemLocale) {
  if (preference === 'zh' || preference === 'en') return preference;
  return /^zh(?:[-_]|$)/i.test(systemLocale || '') ? 'zh' : 'en';
}

function translateEnglish(message) {
  return Object.prototype.hasOwnProperty.call(english, message) ? english[message] : message;
}
const original = message => message;
export const translator = language => language === 'en' ? translateEnglish : original;

// Native failures can include nested steps and numeric OS or HTTP diagnostics.
// Only pass app diagnostics here; subscription node names and user rules are user data.
export function diagnostic(t, message) {
  if (!message || t === original) return message;
  return message.split(/([：；])/).map(part => {
    if (part === '：') return ': ';
    if (part === '；') return ' · ';
    return t(part)
      .replace(/^系统返回 (-?\d+)$/, 'System returned $1')
      .replace(/^启动 Mihomo 失败（(-?\d+)）$/, 'Mihomo failed to start ($1)')
      .replace(/^下载返回 HTTP (\d+)$/, 'Download returned HTTP $1');
  }).join('');
}
